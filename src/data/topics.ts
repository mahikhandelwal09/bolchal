export function getNicheById(id: string): Niche {
  if (id === 'deep-research') return DEEP_RESEARCH_NICHE;
  return NICHES.find((n) => n.id === id) ?? NICHES[0];
}

export function getRandomTopic(topics: string[]): string {
  return topics[Math.floor(Math.random() * topics.length)];
}
